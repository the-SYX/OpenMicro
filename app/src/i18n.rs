//! UI strings: a flat key -> English table.
//!
//! The UI looks text up by key through `tr()`, so call sites stay short and
//! one table holds every visible string. An unknown key shows as "?" (and
//! trips a debug assertion) so the mistake is visible.

/// The English text for a key.
pub fn tr(key: &str) -> &'static str {
    for row in STRINGS {
        if row.0 == key {
            return row.1;
        }
    }
    debug_assert!(false, "missing i18n key: {key}");
    "?"
}

